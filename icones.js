function draw(c, name){
  const ic = ICONS[name], x = c.getContext("2d");
  if (!ic) return;
  if (ic.draw) return ic.draw(x);
  ic.map.forEach((row, r) => [...row].forEach((ch, col) => { if (ic.pal[ch]){ x.fillStyle = ic.pal[ch]; x.fillRect(col, r, 1, 1); } }));
}
